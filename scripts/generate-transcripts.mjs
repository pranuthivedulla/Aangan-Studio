/**
 * Generate src/demo/transcripts.generated.ts from the committed extraction of
 * the September enquiry document.
 *
 * Two problems, one fix.
 *
 * 1. The deployed app must not read the filesystem. `fileURLToPath(new URL(…,
 *    import.meta.url))` breaks once webpack bundles it — the bundled `URL` is
 *    not the class `node:url` expects — and reaching for `process.cwd()`
 *    instead would make a public page depend on where it happens to be run.
 *    Embedding the text removes the question.
 *
 * 2. C11 from the Phase 1 review: `enquiries-extracted.txt` was produced by
 *    hand, with `pdftotext` flags I typed once and could not reproduce. Every
 *    evidence test depends on that text. Now the derived module is generated by
 *    a committed script and a test regenerates it and compares, so drift
 *    fails CI instead of going unnoticed.
 *
 * The PDF-to-text step itself still needs `pdftotext`, which CI does not have,
 * so the extracted text stays committed as the source of truth for the words.
 * This script only derives the TypeScript module from it.
 *
 *   node scripts/generate-transcripts.mjs          # write
 *   node scripts/generate-transcripts.mjs --check  # verify, exit 1 on drift
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const SOURCE = join(root, 'context', 'enquiries', 'enquiries-extracted.txt');
const TARGET = join(root, 'src', 'demo', 'transcripts.generated.ts');

/**
 * Line endings are normalised to LF before embedding.
 *
 * Without this the script is not reproducible across platforms: a Windows
 * working copy holds CRLF, git stores LF, so Linux CI regenerated a different
 * module and --check failed on a file nobody had touched. The embedded text is
 * compared against transcripts character by character to decide whether a
 * caller really said something, so it has to be the same text everywhere.
 */
export function normalise(text) {
  return text.replace(/\r\n/g, '\n');
}

export function buildModule(rawText) {
  rawText = normalise(rawText);
  const header = [
    '/**',
    ' * GENERATED FILE — do not edit.',
    ' *',
    ' * Written by scripts/generate-transcripts.mjs from',
    ' * context/enquiries/enquiries-extracted.txt, which is itself the committed',
    ' * pdftotext extraction of the September enquiry document.',
    ' *',
    ' * It exists so the deployed app never reads the filesystem, and so the text',
    ' * every evidence test depends on is reproducible rather than hand-made.',
    ' * tests/unit/generated-transcripts.test.ts regenerates this and fails on drift.',
    ' */',
    '',
    'export const ENQUIRY_DOCUMENT_TEXT: string =',
  ].join('\n');

  // JSON.stringify gives correct escaping for quotes, backslashes, newlines and
  // the non-ASCII the document contains (em dashes, rupee signs).
  const chunks = [];
  const lines = rawText.split('\n');
  const perChunk = 40;
  for (let i = 0; i < lines.length; i += perChunk) {
    chunks.push(JSON.stringify(lines.slice(i, i + perChunk).join('\n') + (i + perChunk < lines.length ? '\n' : '')));
  }

  return `${header}\n  ${chunks.join(' +\n  ')};\n`;
}

const raw = readFileSync(SOURCE, 'utf8');
const generated = buildModule(raw);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    console.error('transcripts.generated.ts is missing. Run: node scripts/generate-transcripts.mjs');
    process.exit(1);
  }
  if (current !== generated) {
    console.error(
      'transcripts.generated.ts is out of date with context/enquiries/enquiries-extracted.txt.\n' +
        'Run: node scripts/generate-transcripts.mjs',
    );
    process.exit(1);
  }
  console.log('transcripts.generated.ts is up to date.');
} else {
  writeFileSync(TARGET, generated, 'utf8');
  console.log(`wrote ${TARGET} (${generated.length} bytes from ${raw.length} bytes of source)`);
}
