export interface RotaEntrySeed {
  /** ISO date, yyyy-mm-dd. */
  readonly date: string;
  readonly primaryDesignerIds: readonly string[];
  readonly backupDesignerId: string;
}

/**
 * The rota is COMPUTED from the date, not listed.
 *
 * It was two hard-coded days, and a live run found why that was wrong: the
 * dates were in the past, so on any real day nobody was on duty and every
 * caller was told the studio would ring them back. The unit tests never saw
 * it because they pinned the clock to one of the two days.
 *
 * Computing it means every date has an answer, the answer is stable for a
 * given date (so assignment stays deterministic and testable), and Sunday is
 * closed because the studio is. It is still SEED data: the real rota comes
 * from Supabase in Phase 7, and the whole of this file goes then.
 */

/** Days since an arbitrary fixed epoch, used only to rotate the duty pair. */
function dayNumber(dateKey: string): number {
  const [y, m, d] = dateKey.split('-').map(Number);
  return Math.floor(Date.UTC(y ?? 1970, (m ?? 1) - 1, d ?? 1) / 86_400_000);
}

function isoWeekday(dateKey: string): number {
  const [y, m, d] = dateKey.split('-').map(Number);
  return ((new Date(Date.UTC(y ?? 1970, (m ?? 1) - 1, d ?? 1)).getUTCDay() + 6) % 7) + 1;
}

/** Mon-Sat, matching the studio's hours. Sunday nobody is on. */
export const ROTA_WORKING_WEEKDAYS: readonly number[] = [1, 2, 3, 4, 5, 6];

export function onDuty(date: string): RotaEntrySeed | null {
  if (!ROTA_WORKING_WEEKDAYS.includes(isoWeekday(date))) return null;

  const eligible = DESIGNERS.filter((d) => d.eligibleAsDesigner).map((d) => d.id);
  if (eligible.length < 2) return null;

  const offset = ((dayNumber(date) % eligible.length) + eligible.length) % eligible.length;
  const rotated = [...eligible.slice(offset), ...eligible.slice(0, offset)];

  return {
    date,
    primaryDesignerIds: [rotated[0] as string, rotated[1] as string],
    backupDesignerId: (rotated[2] ?? rotated[0]) as string,
  };
}

/**
 * A fixed sample window, for tests that want to walk the rota. Generated by
 * the same function that serves live dates, so the two cannot disagree.
 */
export const ROTA: readonly RotaEntrySeed[] = Array.from({ length: 14 }, (_, i) => {
  const d = new Date(Date.UTC(2026, 9, 12) + i * 86_400_000).toISOString().slice(0, 10);
  return onDuty(d);
}).filter((r): r is RotaEntrySeed => r !== null);

export function designerById(id: string): DesignerSeed {
  const found = DESIGNERS.find((d) => d.id === id);
  if (!found) throw new Error(`Unknown designer id: ${id}`);
  return found;
}

export function eligibleDesignerIds(): readonly string[] {
  return DESIGNERS.filter((d) => d.eligibleAsDesigner).map((d) => d.id);
}
